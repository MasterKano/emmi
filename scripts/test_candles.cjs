/* Tile candles: real OHLC only, line fallback when a row has none, one candle per day / per month. */
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const root = path.join(__dirname, "..");
const store = {};
const ctx = { window: {}, localStorage: { getItem: k => (k in store ? store[k] : null), setItem: (k, v) => { store[k] = String(v); } } };
vm.runInNewContext(fs.readFileSync(path.join(root, "v2/shared/candles.js"), "utf8"), ctx);
const C = ctx.window.MMCandles;
const day = [[10, 11, 9.5, 10.5], [10.5, 10.6, 9.8, 10], [null, null, null, 10.2], [10.2, 10.9, 10.1, 10.8]];
const row = { ohlc: { d: day, d0: "2026-11-09", m: [[9, 10, 8, 9.5], [9.5, 11, 9.4, 10.8]], m0: "2026-10" } };
assert.strictEqual(C.scale(), "d", "daily is the default scale");
const d = C.svg(row, "d");
assert.strictEqual((d.match(/<rect /g) || []).length, 3, "three bars with an open get a body");
assert.ok(/var\(--good\)/.test(d) && /var\(--bad\)/.test(d), "up green, down red");
assert.ok(/stroke="var\(--muted\)"/.test(d), "a bar without an open is a grey close tick, not a body");
assert.ok(/4 daily candles from 9 Nov/.test(d), "daily label");
const m = C.svg(row, "m");
assert.strictEqual((m.match(/<rect /g) || []).length, 2, "one candle per month");
assert.ok(/2 monthly candles from Oct 2026/.test(m), "monthly label");
assert.strictEqual(C.svg({ spark: [1, 2, 3] }, "d"), "", "no OHLC: caller keeps the line");
assert.strictEqual(C.svg({ ohlc: { d: [[null, null, null, 1], [null, null, null, 2]] } }, "d"), "", "closes only: no candles");
assert.strictEqual(C.svg({ ohlc: { d: day } }, "m"), "", "no monthly bars: no monthly candles");
C.setScale("m");
assert.strictEqual(C.scale(), "m", "scale is remembered");
const ui = C.toggle("m");
assert.ok(/data-cdl="m" aria-pressed="true"/.test(ui) && /data-cdl="d" aria-pressed="false"/.test(ui), "switch shows the chosen scale");
const mk = fs.readFileSync(path.join(root, "v2/markets/markets.js"), "utf8");
assert.ok(/C\.svg\(r, C\.scale\(\)\)\) \|\| spark\(r\.spark\)/.test(mk), "markets tiles fall back to the 1Y line");
console.log("Tile candles (daily, monthly, line fallback): PASS");
